function Get-RepositoryRelativePath
{
    param([Parameter(Mandatory = $true)][string]$Path)

    $fullPath = [IO.Path]::GetFullPath($Path)
    $rootWithSeparator = $repositoryRootPath.TrimEnd('\', '/') + [IO.Path]::DirectorySeparatorChar
    if (-not $fullPath.StartsWith($rootWithSeparator, [StringComparison]::OrdinalIgnoreCase))
    {
        throw "Path is outside the repository: $fullPath"
    }

    return $fullPath.Substring($rootWithSeparator.Length).Replace('\', '/')
}

function Read-XmlDocument
{
    param([Parameter(Mandatory = $true)][string]$Path)

    $settings = New-Object Xml.XmlReaderSettings
    $settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
    $settings.XmlResolver = $null

    $reader = [Xml.XmlReader]::Create($Path, $settings)
    try
    {
        $document = New-Object Xml.XmlDocument
        $document.XmlResolver = $null
        $document.Load($reader)
        return $document
    }
    finally
    {
        $reader.Dispose()
    }
}

function Get-ElementChildren
{
    param([Parameter(Mandatory = $true)][Xml.XmlNode]$Node)

    return @($Node.ChildNodes | Where-Object {
        $_.NodeType -eq [Xml.XmlNodeType]::Element
    })
}

function Get-ChildText
{
    param(
        [Parameter(Mandatory = $true)][Xml.XmlElement]$Element,
        [Parameter(Mandatory = $true)][string]$ChildName
    )

    $child = $Element.SelectSingleNode("./$ChildName")
    if ($null -eq $child)
    {
        return ''
    }

    return $child.InnerText.Trim()
}

function ConvertTo-MarkdownCell
{
    param([AllowNull()][string]$Value)

    if ([string]::IsNullOrWhiteSpace($Value))
    {
        return '—'
    }

    $clean = [Text.RegularExpressions.Regex]::Replace($Value, '\s+', ' ').Trim()
    $clean = $clean.Replace('|', '\|').Replace('`', '&#96;')
    return $clean
}

function Get-ObservedFieldShape
{
    param([Parameter(Mandatory = $true)][Xml.XmlElement]$Element)

    $children = @(Get-ElementChildren -Node $Element)
    if ($children.Count -eq 0)
    {
        return 'scalar'
    }

    $nonListChildren = @($children | Where-Object { $_.LocalName -ne 'li' })
    if ($nonListChildren.Count -eq 0)
    {
        return 'list'
    }

    return 'object'
}

function Get-SafePageFileName
{
    param(
        [Parameter(Mandatory = $true)][string]$TypeName,
        [Parameter(Mandatory = $true)][hashtable]$ShortNameCounts
    )

    $shortName = ($TypeName -split '\.')[-1]
    $baseName = if ($ShortNameCounts[$shortName] -gt 1)
    {
        $TypeName.Replace('.', '-')
    }
    else
    {
        $shortName
    }

    $invalidPattern = '[' + [Text.RegularExpressions.Regex]::Escape(
        [string]::Join('', [IO.Path]::GetInvalidFileNameChars())) + ']'
    $safeName = [Text.RegularExpressions.Regex]::Replace($baseName, $invalidPattern, '-')
    return "$safeName.md"
}

function Get-SourceFingerprint
{
    param([Parameter(Mandatory = $true)][IO.FileInfo[]]$Files)

    $builder = New-Object Text.StringBuilder
    foreach ($file in @($Files | Sort-Object FullName))
    {
        $relativePath = Get-RepositoryRelativePath -Path $file.FullName
        $content = [IO.File]::ReadAllText($file.FullName).Replace("`r`n", "`n").Replace("`r", "`n")
        [void]$builder.Append($relativePath).Append("`n").Append($content).Append("`n")
    }

    $utf8 = New-Object Text.UTF8Encoding($false)
    $sha256 = [Security.Cryptography.SHA256]::Create()
    try
    {
        $hash = $sha256.ComputeHash($utf8.GetBytes($builder.ToString()))
        return ([BitConverter]::ToString($hash).Replace('-', '').ToLowerInvariant()).Substring(0, 16)
    }
    finally
    {
        $sha256.Dispose()
    }
}

function Normalize-GeneratedText
{
    param([Parameter(Mandatory = $true)][string]$Content)

    return $Content.Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd() + "`n"
}

function Write-Utf8NoBom
{
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Content
    )

    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent))
    {
        [void](New-Item -ItemType Directory -Path $parent -Force)
    }

    $utf8 = New-Object Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($Path, (Normalize-GeneratedText -Content $Content), $utf8)
}

# Def text is commonly localized through DefInjected instead of a literal <label> in 1.6/Defs.
# Build a single lookup so each generated row can show the shipped English label when one exists.
$englishValues = @{}
foreach ($languageFile in @(Get-ChildItem -LiteralPath $englishDefInjectedRoot -Recurse -File -Filter '*.xml' |
    Sort-Object FullName))
{
    $languageDocument = Read-XmlDocument -Path $languageFile.FullName
    if ($null -eq $languageDocument.DocumentElement -or
        $languageDocument.DocumentElement.LocalName -ne 'LanguageData')
    {
        continue
    }

    foreach ($entry in @(Get-ElementChildren -Node $languageDocument.DocumentElement))
    {
        $englishValues[$entry.LocalName] = $entry.InnerText.Trim()
    }
}

$xmlFiles = @(Get-ChildItem -LiteralPath $defsRoot -Recurse -File -Filter '*.xml' | Sort-Object FullName)
$records = New-Object System.Collections.Generic.List[object]
$parsedDefFiles = New-Object System.Collections.Generic.List[object]

foreach ($xmlFile in $xmlFiles)
{
    $document = Read-XmlDocument -Path $xmlFile.FullName
    if ($null -eq $document.DocumentElement -or $document.DocumentElement.LocalName -ne 'Defs')
    {
        continue
    }

    $relativePath = Get-RepositoryRelativePath -Path $xmlFile.FullName
    [void]$parsedDefFiles.Add($xmlFile)
    foreach ($element in @(Get-ElementChildren -Node $document.DocumentElement))
    {
        $typeName = $element.LocalName
        $shortTypeName = ($typeName -split '\.')[-1]
        $defName = Get-ChildText -Element $element -ChildName 'defName'
        $label = Get-ChildText -Element $element -ChildName 'label'
        if ([string]::IsNullOrWhiteSpace($label) -and -not [string]::IsNullOrWhiteSpace($defName))
        {
            $labelKey = "$defName.label"
            if ($englishValues.ContainsKey($labelKey))
            {
                $label = [string]$englishValues[$labelKey]
            }
        }

        $abstractName = $element.GetAttribute('Name')
        $isAbstract = [string]::Equals(
            $element.GetAttribute('Abstract'),
            'True',
            [StringComparison]::OrdinalIgnoreCase)
        $displayName = if (-not [string]::IsNullOrWhiteSpace($defName))
        {
            $defName
        }
        elseif (-not [string]::IsNullOrWhiteSpace($abstractName))
        {
            "abstract: $abstractName"
        }
        else
        {
            'unnamed record'
        }

        [void]$records.Add([pscustomobject]@{
            TypeName = $typeName
            ShortTypeName = $shortTypeName
            DefName = $defName
            DisplayName = $displayName
            Label = $label
            ParentName = $element.GetAttribute('ParentName')
            AbstractName = $abstractName
            IsAbstract = $isAbstract
            XmlPath = $relativePath
            Element = $element
        })
    }
}

if ($records.Count -eq 0)
{
    throw "No Def records were found below $defsRoot"
}

$sourceFiles = @(Get-ChildItem -LiteralPath $sourceRoot -Recurse -File -Filter '*.cs' | Sort-Object FullName)
$sourceContents = @{}
foreach ($sourceFile in $sourceFiles)
{
    $sourceContents[$sourceFile.FullName] = [IO.File]::ReadAllText($sourceFile.FullName)
}

$typeNames = @($records | Select-Object -ExpandProperty TypeName -Unique | Sort-Object)
$shortNameCounts = @{}
foreach ($typeName in $typeNames)
{
    $shortName = ($typeName -split '\.')[-1]
    if (-not $shortNameCounts.ContainsKey($shortName))
    {
        $shortNameCounts[$shortName] = 0
    }
    $shortNameCounts[$shortName]++
}

$implementationPathsByType = @{}
foreach ($typeName in $typeNames)
{
    $shortName = ($typeName -split '\.')[-1]
    $pattern = '\bclass\s+' + [Text.RegularExpressions.Regex]::Escape($shortName) + '\b'
    $matches = New-Object System.Collections.Generic.List[string]
    foreach ($sourceFile in $sourceFiles)
    {
        if ([Text.RegularExpressions.Regex]::IsMatch($sourceContents[$sourceFile.FullName], $pattern))
        {
            [void]$matches.Add((Get-RepositoryRelativePath -Path $sourceFile.FullName))
        }
    }
    $implementationPathsByType[$typeName] = @($matches | Sort-Object -Unique)
}

$implementationFiles = @($implementationPathsByType.Values |
    ForEach-Object { $_ } |
    Sort-Object -Unique |
    ForEach-Object { Get-Item -LiteralPath (Join-Path $repositoryRootPath $_) })
$sourceFingerprint = Get-SourceFingerprint -Files @($parsedDefFiles + $implementationFiles)
$namedRecordCount = @($records | Where-Object { -not [string]::IsNullOrWhiteSpace($_.DefName) }).Count
$abstractRecordCount = @($records | Where-Object { $_.IsAbstract }).Count

$desiredPages = @{}

