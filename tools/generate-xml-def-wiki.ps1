$desiredPages[$xmlLandingPath] = $landing.ToString()

$problems = New-Object System.Collections.Generic.List[string]
foreach ($pagePath in @($desiredPages.Keys | Sort-Object))
{
    $expected = Normalize-GeneratedText -Content ([string]$desiredPages[$pagePath])
    if (-not (Test-Path -LiteralPath $pagePath))
    {
        [void]$problems.Add("Missing generated page: $(Get-RepositoryRelativePath -Path $pagePath)")
        continue
    }

    $actual = [IO.File]::ReadAllText($pagePath).Replace("`r`n", "`n").Replace("`r", "`n")
    if ($actual -ne $expected)
    {
        [void]$problems.Add("Stale generated page: $(Get-RepositoryRelativePath -Path $pagePath)")
    }
}

if (Test-Path -LiteralPath $generatedReferenceRoot)
{
    foreach ($existingPage in @(Get-ChildItem -LiteralPath $generatedReferenceRoot -File -Filter '*.md'))
    {
        if (-not $desiredPages.ContainsKey($existingPage.FullName))
        {
            $content = [IO.File]::ReadAllText($existingPage.FullName)
            if ($content.StartsWith($generatedMarker, [StringComparison]::Ordinal))
            {
                [void]$problems.Add("Obsolete generated page: $(Get-RepositoryRelativePath -Path $existingPage.FullName)")
            }
            else
            {
                throw "Refusing to manage an unmarked page in the generated directory: $($existingPage.FullName)"
            }
        }
    }
