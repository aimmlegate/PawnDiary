if ($Check)
{
    if ($problems.Count -gt 0)
    {
        throw "XML Def wiki check failed:`n - $($problems -join "`n - ")"
    }

    Write-Output "XML Def wiki is current: $($parsedDefFiles.Count) files, $($typeNames.Count) types, $namedRecordCount named records, fingerprint $sourceFingerprint."
    exit 0
}

if (-not (Test-Path -LiteralPath $generatedReferenceRoot))
{
    [void](New-Item -ItemType Directory -Path $generatedReferenceRoot -Force)
}

foreach ($existingPage in @(Get-ChildItem -LiteralPath $generatedReferenceRoot -File -Filter '*.md'))
{
    if ($desiredPages.ContainsKey($existingPage.FullName))
    {
        continue
    }

    $content = [IO.File]::ReadAllText($existingPage.FullName)
    if (-not $content.StartsWith($generatedMarker, [StringComparison]::Ordinal))
    {
        throw "Refusing to delete an unmarked page in the generated directory: $($existingPage.FullName)"
    }

    Remove-Item -LiteralPath $existingPage.FullName
}

foreach ($pagePath in @($desiredPages.Keys | Sort-Object))
{
    Write-Utf8NoBom -Path $pagePath -Content ([string]$desiredPages[$pagePath])
}

Write-Output "Regenerated XML Def wiki: $($parsedDefFiles.Count) files, $($typeNames.Count) types, $namedRecordCount named records, fingerprint $sourceFingerprint."
