    [void]$page.AppendLine()
    [void]$page.AppendLine('[Generated reference index](Generated%20Def%20Reference.md) · [XML Definition System](../XML%20Definition%20System.md)')
    [void]$page.AppendLine()
    [void]$page.AppendLine('## Source XML')
    [void]$page.AppendLine()
    foreach ($sourcePath in $sourcePaths)
    {
        $label = Split-Path -Leaf $sourcePath
        [void]$page.AppendLine("- [$label](../../../../../../$sourcePath)")
    }
    [void]$page.AppendLine()
    [void]$page.AppendLine('## Instances')
    [void]$page.AppendLine()
    [void]$page.AppendLine('| defName or parent | English label | ParentName | Source |')
    [void]$page.AppendLine('|---|---|---|---|')
    foreach ($record in $typeRecords)
    {
        $sourceLabel = Split-Path -Leaf $record.XmlPath
        $sourceLink = "[$sourceLabel](../../../../../../$($record.XmlPath))"
        [void]$page.AppendLine(
            "| ``$(ConvertTo-MarkdownCell -Value $record.DisplayName)`` | " +
            "$(ConvertTo-MarkdownCell -Value $record.Label) | " +
            "``$(ConvertTo-MarkdownCell -Value $record.ParentName)`` | $sourceLink |")
    }

    $fieldObservations = New-Object System.Collections.Generic.List[object]
    foreach ($record in $typeRecords)
    {
        $seenFields = @{}
        foreach ($field in @(Get-ElementChildren -Node $record.Element))
        {
            if ($field.LocalName -eq 'defName' -or $field.LocalName -eq 'label')
            {
                continue
            }
            if ($seenFields.ContainsKey($field.LocalName))
            {
                continue
            }
            $seenFields[$field.LocalName] = $true
            [void]$fieldObservations.Add([pscustomobject]@{
                FieldName = $field.LocalName
                Shape = Get-ObservedFieldShape -Element $field
            })
        }
    }

    [void]$page.AppendLine()
    [void]$page.AppendLine('## Observed top-level XML fields')
    [void]$page.AppendLine()
    [void]$page.AppendLine('This is an inventory of fields present in the shipped XML, not a replacement for the C# schema.')
    [void]$page.AppendLine('Code fallbacks, inherited fields, and optional extension fields may not appear here.')
    [void]$page.AppendLine()
    [void]$page.AppendLine('| Field | Present on records | Observed shape |')
    [void]$page.AppendLine('|---|---:|---|')
    foreach ($fieldGroup in @($fieldObservations | Group-Object FieldName | Sort-Object Name))
    {
        $shapes = @($fieldGroup.Group | Select-Object -ExpandProperty Shape -Unique | Sort-Object)
        [void]$page.AppendLine(
            "| ``$(ConvertTo-MarkdownCell -Value $fieldGroup.Name)`` | $($fieldGroup.Count) / $($typeRecords.Count) | $($shapes -join ', ') |")
    }

    $desiredPages[$pagePath] = $page.ToString()
}

