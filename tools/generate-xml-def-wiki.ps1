#requires -Version 5.1

<#
.SYNOPSIS
Regenerates the source-backed XML Def reference in repowiki/.

.DESCRIPTION
The hand-written wiki explains behavior, while this script owns the mechanical inventory of the
current XML Def files. It parses every XML file below 1.6/Defs, resolves English DefInjected labels
when available, locates matching C# Def declarations below Source, and writes:

- the XML Definition System landing page;
- the Generated Def Reference index;
- one generated reference page per XML Def type.

Use -Check in validation jobs to fail when committed generated pages differ from the current source.
The script never touches pages outside its generated landing page and generated-reference folder.

.EXAMPLE
powershell -ExecutionPolicy Bypass -File tools/generate-xml-def-wiki.ps1

.EXAMPLE
powershell -ExecutionPolicy Bypass -File tools/generate-xml-def-wiki.ps1 -Check
#>

