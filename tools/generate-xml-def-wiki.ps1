    [void]$index.AppendLine(
        "| [``$(ConvertTo-MarkdownCell -Value $typeName)``]($pageFileName) | $($typeRecords.Count) | $fileCount | $implementationCell |")
}

$desiredPages[$generatedReferenceIndexPath] = $index.ToString()

foreach ($typeName in $typeNames)
{
    $typeRecords = @($records | Where-Object { $_.TypeName -eq $typeName } |
        Sort-Object DisplayName, XmlPath)
    $pageFileName = Get-SafePageFileName -TypeName $typeName -ShortNameCounts $shortNameCounts
    $pagePath = Join-Path $generatedReferenceRoot $pageFileName
    $implementations = @($implementationPathsByType[$typeName])
    $sourcePaths = @($typeRecords | Select-Object -ExpandProperty XmlPath -Unique | Sort-Object)

    $page = New-Object Text.StringBuilder
    [void]$page.AppendLine($generatedMarker)
    [void]$page.AppendLine()
    [void]$page.AppendLine("# $(($typeName -split '\.')[-1])")
