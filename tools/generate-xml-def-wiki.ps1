    [void]$page.AppendLine("- Records in the shipped Def catalog: **$($typeRecords.Count)**")
    [void]$page.AppendLine("- Source fingerprint: ``$sourceFingerprint``")
    if ($implementations.Count -gt 0)
    {
        $implementationLinks = @($implementations | ForEach-Object {
            $label = Split-Path -Leaf $_
            "[$label](../../../../../../$_)"
