[void]$index.AppendLine('declarations under `Source/`. It inventories what is actually shipped; hand-written')
[void]$index.AppendLine('behavior pages remain responsible for explaining runtime semantics.')
[void]$index.AppendLine()
[void]$index.AppendLine("- Source fingerprint: ``$sourceFingerprint``")
[void]$index.AppendLine("- Parsed XML files: **$($parsedDefFiles.Count)**")
[void]$index.AppendLine("- XML Def types: **$($typeNames.Count)**")
[void]$index.AppendLine("- Named Def instances: **$namedRecordCount**")
[void]$index.AppendLine("- Abstract XML parents: **$abstractRecordCount**")
[void]$index.AppendLine()
[void]$index.AppendLine('[Back to XML Definition System](../XML%20Definition%20System.md)')
[void]$index.AppendLine()
[void]$index.AppendLine('## Def types')
[void]$index.AppendLine()
[void]$index.AppendLine('| XML type | Records | XML files | C# declaration |')
[void]$index.AppendLine('|---|---:|---:|---|')

foreach ($typeName in $typeNames)
{
    $typeRecords = @($records | Where-Object { $_.TypeName -eq $typeName } |
        Sort-Object DisplayName, XmlPath)
    $fileCount = @($typeRecords | Select-Object -ExpandProperty XmlPath -Unique).Count
    $pageFileName = Get-SafePageFileName -TypeName $typeName -ShortNameCounts $shortNameCounts
    $implementations = @($implementationPathsByType[$typeName])
    $implementationCell = if ($implementations.Count -eq 0)
    {
        'RimWorld/Verse'
    }
    else
    {
        @($implementations | ForEach-Object {
            $label = Split-Path -Leaf $_
            "[$label](../../../../../../$_)"
        }) -join '<br>'
